"""Программы освоения навыков: 4 недели × 3 тренировки, последняя — испытание.

Прогрессии собраны по открытым гайдам калистеники (r/bodyweightfitness, GMB,
Gymnastic Bodies и др.). Источники сходятся в порядке шагов, но не в цифрах,
поэтому объёмы взяты консервативно: связки и сухожилия адаптируются медленнее мышц.
"""
from dataclasses import dataclass, replace

from game import Branch, Equipment

WEEKS = 4
SESSIONS_PER_WEEK = 3
TOTAL_SESSIONS = WEEKS * SESSIONS_PER_WEEK
SESSION_XP = 40
PROGRAM_XP = 300
SKILL_REST_SECONDS = 90


@dataclass(frozen=True)
class Drill:
    name: str
    seconds: bool      # True — удержание на время, False — повторы
    sets: int
    value: int
    tip: str
    guide: str = ""    # id ступени из game.STEPS, если есть подробная техника
    per_side: bool = False

    def fmt(self, value=None) -> str:
        v = self.value if value is None else value
        return f"{v} с" if self.seconds else str(v)

    @property
    def scheme(self) -> str:
        side = " на сторону" if self.per_side else ""
        return f"{self.sets} × {self.fmt()}{side}"

    def scaled(self, factor: float) -> "Drill":
        """Облегчённая версия: подходы те же, повторы/секунды меньше. Одиночные попытки не меняются."""
        if factor == 1.0 or self.value <= 1:
            return self
        value = max(3, round(self.value * factor)) if self.seconds else max(1, round(self.value * factor))
        return replace(self, value=min(value, self.value))


@dataclass(frozen=True)
class Week:
    focus: str
    drills: tuple


@dataclass(frozen=True)
class Program:
    id: str
    name: str
    goal: str
    icon: str          # ключ иконки, сопоставляется в интерфейсе
    branch: Branch     # в характеристику какой ветки идёт XP
    difficulty: str
    equipment: frozenset
    prereq: str
    description: str
    weeks: tuple
    test: tuple
    category: str = "Сила"  # тип навыка для фильтра каталога: Сила, Баланс, Гибкость, Пресс

    def available_with(self, equipment: set) -> bool:
        return all(e in equipment for e in self.equipment)

    def session(self, index: int, factor: float = 1.0) -> tuple:
        """Упражнения тренировки по её номеру (0…11). Последняя — испытание."""
        if index >= TOTAL_SESSIONS - 1:
            drills = self.test
        else:
            drills = self.weeks[min(index // SESSIONS_PER_WEEK, WEEKS - 1)].drills
        return tuple(d.scaled(factor) for d in drills)

    @staticmethod
    def week_of(index: int) -> int:
        return min(index // SESSIONS_PER_WEEK, WEEKS - 1) + 1


def D(name, seconds, sets, value, tip, guide="", side=False):
    return Drill(name, seconds, sets, value, tip, guide, side)


